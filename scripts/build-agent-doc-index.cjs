"use strict";
const fs = require("node:fs"), path = require("node:path"), crypto = require("node:crypto");
const root = path.resolve(__dirname, "..");
const outputPath = path.join(root, "editor/src/assistant/agentvnDocIndex.generated.ts");
const manifestPath = "docs/assistant-knowledge-sources.json";
const guidePath = "docs/ASSISTANT_USER_GUIDE.md";
const helpPath = "editor/src/components/common/hoverHelpCatalog.ts";
const hash = value => crypto.createHash("sha256").update(value).digest("hex");
const sourceHash = file => hash(fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n"));
const slug = value => value.toLowerCase().replace(/[^a-z0-9\u3400-\u9fff]+/g, "-").replace(/^-|-$/g, "");
function listMarkdownDocuments(sourceRoot = root) {
  const manifest = JSON.parse(fs.readFileSync(path.join(sourceRoot, manifestPath), "utf8"));
  if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.markdown)
    || !manifest.markdown.length || new Set(manifest.markdown).size !== manifest.markdown.length)
    throw Error("ASSISTANT_SOURCE_MANIFEST_INVALID");
  const resolvedRoot = fs.realpathSync(sourceRoot);
  return [...manifest.markdown].sort().map(file => {
    if (typeof file !== "string" || !/^(docs|editor\/docs|GameCli_framework\/docs)\/.+\.md$/.test(file)
      || file.includes("\\") || file.split("/").some(part => part === ".." || part === "." || !part))
      throw Error(`ASSISTANT_SOURCE_PATH_INVALID: ${file}`);
    const absolute = path.join(sourceRoot, file);
    if (!fs.lstatSync(absolute).isFile()) throw Error(`ASSISTANT_SOURCE_NOT_FILE: ${file}`);
    const relative = path.relative(resolvedRoot, fs.realpathSync(absolute));
    if (relative.startsWith(".." + path.sep) || path.isAbsolute(relative))
      throw Error(`ASSISTANT_SOURCE_OUTSIDE_ROOT: ${file}`);
    return absolute;
  });
}
// Retain every character, including the tail of long sections.
function splitMarkdownText(text, source) {
  const normalized = text.replace(/\r\n/g, "\n");
  const title = normalized.match(/^#\s+(.+)$/m)?.[1] ?? path.basename(source, ".md");
  return normalized.split(/(?=^##\s+)/m).filter(Boolean).flatMap((section, sectionIndex) => {
    const heading = section.match(/^##\s+(.+)$/m)?.[1] ?? title;
    const guide = source === guidePath && /^([a-z-]+)\s+\|/.exec(heading);
    const id = guide ? `guide-${guide[1]}` : `doc-${slug(source)}-${sectionIndex + 1}`;
    const parts = [];
    for (let start = 0; start < section.length;) {
      let end = Math.min(section.length, start + 1800);
      if (end < section.length && /[\uD800-\uDBFF]/.test(section[end - 1])) end--;
      parts.push({ id: `${id}-${parts.length + 1}`, source,
        title: guide ? heading.replace(/^[a-z-]+\s+\|\s*/, "") : `${title} / ${heading}`,
        tags: guide ? ["current-operation-guide", guide[1]] : ["reference", ...source.split("/").slice(0, -1)],
        text: section.slice(start, end) });
      start = end;
    }
    return parts;
  });
}
function build() {
  const docs = listMarkdownDocuments();
  const chunks = [], sources = [];
  for (const file of docs) {
    const text = fs.readFileSync(file, "utf8"), source = path.relative(root, file).replace(/\\/g, "/");
    const sections = splitMarkdownText(text, source);
    chunks.push(...sections);
    sources.push({ path: source, sha256: sourceHash(file), characters: text.replace(/\r\n/g, "\n").length, chunks: sections.length });
  }
  // Load the project's own data module. Regex missed quickHelp() and merged entries.
  const mod = { exports: {} };
  const code = require(require.resolve("esbuild", { paths: [path.join(root, "editor")] })).buildSync({
    entryPoints: [path.join(root, helpPath)], bundle: true, format: "cjs", platform: "node", write: false,
  }).outputFiles[0].text;
  new Function("module", "exports", "require", code)(mod, mod.exports, require);
  const catalog = mod.exports.hoverHelpCatalog;
  if (!catalog || Object.keys(catalog).length < 100) throw Error("Incomplete real help catalog");
  for (const [key, entry] of Object.entries(catalog)) {
    const body = Object.entries(entry).filter(([name, value]) => name !== "title" && typeof value === "string")
      .map(([name, value]) => `${name}: ${value}`).join("\n");
    chunks.push({ id: `help-${key}`, source: helpPath, title: `控件帮助：${entry.title}`,
      tags: ["control-help", key], text: `帮助键：${key}\n${body}` });
  }
  sources.push({ path: helpPath, sha256: sourceHash(path.join(root, helpPath)),
    chunks: Object.keys(catalog).length });
  if (new Set(chunks.map(chunk => chunk.id)).size !== chunks.length || chunks.length < 100)
    throw Error("Duplicate or empty knowledge index");
  const metadata = { schemaVersion: 2, sourceHashEncoding: "utf8-lf",
    generatorSha256: sourceHash(__filename),
    sourceManifestSha256: sourceHash(path.join(root, manifestPath)), sources };
  return { chunks, metadata, output: [
    "/* Auto-generated by scripts/build-agent-doc-index.cjs. Do not edit manually. */",
    'import type { AssistantDocChunk } from "./types";',
    `export const agentvnDocIndexMetadata = ${JSON.stringify(metadata, null, 2)};`,
    `export const agentvnDocIndex: readonly AssistantDocChunk[] = ${JSON.stringify(chunks, null, 2)};`,
    "",
  ].join("\n") };
}
function main() {
  const result = build();
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8").replace(/\r\n/g, "\n") !== result.output)
      throw Error("ASSISTANT_INDEX_STALE: Run node scripts/build-agent-doc-index.cjs before building.");
  } else fs.writeFileSync(outputPath, result.output, "utf8");
  console.log(JSON.stringify({ status: "PASS", mode: process.argv.includes("--check") ? "check" : "generate",
    chunks: result.chunks.length, sources: result.metadata.sources.length }));
}
module.exports = { splitMarkdownText, listMarkdownDocuments, build };
if (require.main === module) {
  try { main(); } catch (error) { console.error(String(error)); process.exitCode = 1; }
}
