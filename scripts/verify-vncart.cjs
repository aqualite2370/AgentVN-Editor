const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

function requireFromCandidates(candidates) {
  const errors = [];
  for (const candidate of candidates) {
    try {
      return require(candidate);
    } catch (error) {
      errors.push(`${candidate}: ${error.message}`);
    }
  }
  throw new Error(`Unable to load jszip. Tried: ${errors.join(" | ")}`);
}

const JSZip = requireFromCandidates([
  "../editor/node_modules/jszip",
  "../GameCli_framework/node_modules/jszip",
  "jszip",
]);

const root = path.resolve(__dirname, "..");
const defaultCartridge = path.join(root, "output", "cartridges", "agentvn-sample-0.1.0.vncart");
const rawArgs = process.argv.slice(2);
const allowPlaceholderAssets =
  rawArgs.includes("--allow-placeholder-assets") ||
  process.env.AGENTVN_ALLOW_PLACEHOLDER_ASSETS === "1";
const reportIndex = rawArgs.indexOf("--report");
const reportPath = reportIndex >= 0 ? rawArgs[reportIndex + 1] : "";
if (reportIndex >= 0 && (!reportPath || reportPath.startsWith("--"))) {
  throw new Error("--report requires a file path.");
}
const positionalArgs = rawArgs.filter((arg, index) => {
  if (arg === "--report" || (reportIndex >= 0 && index === reportIndex + 1)) return false;
  return !arg.startsWith("--");
});
const cartridgePath = path.resolve(positionalArgs[0] ?? defaultCartridge);

const requiredFiles = ["manifest.json", "script.json", "checksum.json"];
const dangerousExtensions = [".exe", ".dll", ".bat", ".cmd", ".sh", ".ps1", ".msi", ".app", ".apk", ".jar"];

function fail(message) {
  throw new Error(message);
}

function sha256(buffer) {
  return crypto.createHash("sha256").update(buffer).digest("hex");
}

function writeJsonAtomic(filePath, value) {
  const resolved = path.resolve(filePath);
  const temporary = `${resolved}.tmp-${process.pid}-${Date.now()}`;
  fs.mkdirSync(path.dirname(resolved), { recursive: true });
  fs.writeFileSync(temporary, `${JSON.stringify(value, null, 2)}\n`, { encoding: "utf8", flag: "w" });
  fs.renameSync(temporary, resolved);
}

function publishReport(value) {
  if (reportPath) writeJsonAtomic(reportPath, value);
  process.stdout.write(`${JSON.stringify(value, null, 2)}\n`);
}

function unsafePathReason(filePath) {
  if (filePath.includes("\0")) return "contains a null byte";
  if (filePath.startsWith("/") || filePath.startsWith("\\")) return "uses an absolute path";
  if (/^[a-zA-Z]:/.test(filePath)) return "contains a Windows drive prefix";
  if (filePath.includes("\\")) return "uses backslashes";
  if (filePath.split("/").includes("..")) return "contains a parent directory segment";
  return undefined;
}

function dangerousExtension(filePath) {
  const lowerPath = filePath.toLowerCase();
  return dangerousExtensions.find((ext) => lowerPath.endsWith(ext));
}

async function readFileAsStreamBuffer(filePath, maxBytes = 2048 * 1024 * 1024) {
  const chunks = [];
  let total = 0;
  await new Promise((resolve, reject) => {
    const stream = fs.createReadStream(filePath, { highWaterMark: 64 * 1024 });
    stream.on("data", (chunk) => {
      total += chunk.byteLength;
      if (total > maxBytes) {
        stream.destroy(new Error("Cartridge package is larger than the 2GB verification limit."));
        return;
      }
      chunks.push(chunk);
    });
    stream.on("error", reject);
    stream.on("end", resolve);
  });
  return Buffer.concat(chunks, total);
}

async function readJson(zip, filePath) {
  const file = zip.file(filePath);
  if (!file) fail(`Cartridge is missing required file: ${filePath}. Re-export the .vncart from AgentVN.`);
  try {
    return JSON.parse(await file.async("string"));
  } catch (error) {
    fail(`Failed to parse ${filePath}: ${error.message}. Re-export the .vncart from AgentVN.`);
  }
}

function checksumEntry(filePath, data) {
  const buffer = Buffer.isBuffer(data) ? data : Buffer.from(String(data));
  return {
    path: filePath,
    size_bytes: buffer.byteLength,
    hash_sha256: sha256(buffer),
  };
}

async function createSampleCartridge(filePath) {
  const now = new Date().toISOString();
  const zip = new JSZip();
  const entries = [];
  const add = (entryPath, data) => {
    zip.file(entryPath, data);
    entries.push(checksumEntry(entryPath, data));
  };
  const assetData = "AgentVN sample cartridge placeholder background.\n";
  const assetPath = "assets/backgrounds/sample_bg.txt";
  const manifest = {
    manifest_version: "1.0.0",
    cartridge_version: "1.0.0",
    runtime_version: "0.1.0",
    game_id: "agentvn_sample",
    title: "AgentVN Sample Cartridge",
    author: "AgentVN",
    description: "Minimal cartridge generated by verify-vncart.cjs.",
    version: "0.1.0",
    language: "zh-CN",
    tags: ["sample", "verification"],
    entry_script: "script.json",
    entry_scene_id: "scene_start",
    assets: [{
      asset_id: "sample_bg",
      asset_type: "background",
      path: assetPath,
      filename: "sample_bg.txt",
      mime_type: "text/plain",
      size_bytes: Buffer.byteLength(assetData),
      hash_sha256: sha256(Buffer.from(assetData)),
      preload: true,
      tags: ["sample"],
    }],
    created_at: now,
    updated_at: now,
  };
  const script = {
    schema_version: "1.0.0",
    game_id: manifest.game_id,
    title: manifest.title,
    entry_scene_id: "scene_start",
    scenes: [{
      scene_id: "scene_start",
      title: "Start",
      summary: "Minimal playable scene.",
      chapter: 1,
      tags: ["sample"],
      commands: [
        { type: "background", background_id: "sample_bg", transition: "fade" },
        { type: "narration", text: "AgentVN cartridge verification scene." },
      ],
      is_ending: true,
      ending_id: "ending_sample",
    }],
  };
  add("manifest.json", JSON.stringify(manifest, null, 2));
  add("script.json", JSON.stringify(script, null, 2));
  add("gallery.json", JSON.stringify({ gallery_version: "1.0.0", items: [] }, null, 2));
  add(assetPath, assetData);
  const checksum = {
    checksum_version: "1.0.0",
    algorithm: "sha256",
    generated_at: now,
    files: entries.sort((a, b) => a.path.localeCompare(b.path)),
  };
  zip.file("checksum.json", JSON.stringify(checksum, null, 2));
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" }));
}

function validateScript(script) {
  const errors = [];
  const scenes = Array.isArray(script.scenes) ? script.scenes : [];
  const sceneIds = new Set(scenes.map((scene) => scene.scene_id));
  if (!script.schema_version) errors.push("script.json is missing schema_version.");
  if (!Array.isArray(script.scenes)) errors.push("script.json scenes must be an array.");
  if (!sceneIds.has(script.entry_scene_id)) {
    errors.push(`entry_scene_id points to a missing scene: ${script.entry_scene_id || "(empty)"}.`);
  }
  if (sceneIds.size !== scenes.length) errors.push("scene_id values must be unique.");
  for (const scene of scenes) {
    if (scene.next_scene_id && !sceneIds.has(scene.next_scene_id)) {
      errors.push(`Scene ${scene.scene_id} has an invalid next_scene_id: ${scene.next_scene_id}.`);
    }
    if (!Array.isArray(scene.commands)) {
      errors.push(`Scene ${scene.scene_id} commands must be an array.`);
      continue;
    }
    for (const command of scene.commands) {
      if (command.type === "show_image") {
        if (typeof command.image_id !== "string" || !command.image_id.trim()) {
          errors.push(`Scene ${scene.scene_id} has a show_image command without image_id.`);
        }
        if (command.image_fit !== undefined && !["contain", "cover", "stretch"].includes(command.image_fit)) {
          errors.push(`Scene ${scene.scene_id} has an invalid show_image.image_fit: ${command.image_fit}.`);
        }
        if (command.backdrop_opacity !== undefined && (!Number.isFinite(command.backdrop_opacity) || command.backdrop_opacity < 0 || command.backdrop_opacity > 0.9)) {
          errors.push(`Scene ${scene.scene_id} has show_image.backdrop_opacity outside 0..0.9.`);
        }
        if (command.backdrop_blur_px !== undefined && (!Number.isFinite(command.backdrop_blur_px) || command.backdrop_blur_px < 0 || command.backdrop_blur_px > 24)) {
          errors.push(`Scene ${scene.scene_id} has show_image.backdrop_blur_px outside 0..24.`);
        }
      }
      if (command.type !== "choice") continue;
      for (const choice of command.choices ?? []) {
        if (!sceneIds.has(choice.target_scene_id)) {
          errors.push(`Choice ${choice.choice_id || "(unnamed)"} in scene ${scene.scene_id} targets a missing scene: ${choice.target_scene_id || "(empty)"}.`);
        }
      }
    }
  }
  return errors;
}

function collectAssetRefs(script) {
  const refs = new Set();
  const loadingAnimation = script.loading_animation;
  if (loadingAnimation?.kind === "video" && loadingAnimation.video_asset_id) refs.add(loadingAnimation.video_asset_id);
  if (loadingAnimation?.kind === "image_sequence") {
    for (const assetId of loadingAnimation.image_asset_ids ?? []) if (assetId) refs.add(assetId);
  }
  for (const track of script.opening_audio ?? []) {
    if (track?.asset_id) refs.add(track.asset_id);
  }
  for (const scene of script.scenes ?? []) {
    for (const command of scene.commands ?? []) {
      if (command.type === "background") refs.add(command.background_id);
      if (command.type === "show_image") refs.add(command.image_id);
      if (command.type === "sprite") refs.add(command.sprite_id);
      if (command.type === "dialog") {
        if (command.portrait) refs.add(command.portrait);
        if (command.voice) refs.add(command.voice);
        if (command.font_asset_id) refs.add(command.font_asset_id);
      }
      if (command.type === "narration" && command.font_asset_id) refs.add(command.font_asset_id);
      if (command.type === "bgm" && command.bgm_id) refs.add(command.bgm_id);
      if (command.type === "sfx") refs.add(command.sfx_id);
      // animation_id names a runtime effect preset or command-local keyframes, not a packaged asset file.
    }
  }
  return [...refs].filter(Boolean);
}

function isPlaceholderAsset(asset) {
  return Boolean(asset?.placeholder || asset?.tags?.includes("placeholder") || asset?.tags?.includes("missing"));
}

function addAssetIssue({ errors, warnings, message, placeholderSafe = false }) {
  if (placeholderSafe && allowPlaceholderAssets) {
    warnings.push(message);
    return;
  }
  errors.push(message);
}

async function main() {
  if (!fs.existsSync(cartridgePath) && positionalArgs[0] === undefined) {
    await createSampleCartridge(cartridgePath);
  }
  if (!fs.existsSync(cartridgePath)) fail(`Cartridge file does not exist: ${cartridgePath}.`);

  const buffer = await readFileAsStreamBuffer(cartridgePath);
  const zip = await JSZip.loadAsync(buffer);
  const paths = Object.keys(zip.files).filter((filePath) => !zip.files[filePath].dir);

  const errors = [];
  const warnings = [];
  for (const filePath of requiredFiles) {
    if (!paths.includes(filePath)) errors.push(`Cartridge is missing required file: ${filePath}.`);
  }
  for (const filePath of paths) {
    const unsafeReason = unsafePathReason(filePath);
    if (unsafeReason) errors.push(`Unsafe cartridge path ${filePath}: ${unsafeReason}.`);
    const ext = dangerousExtension(filePath);
    if (ext) errors.push(`Cartridge contains a disallowed executable file (${ext}): ${filePath}.`);
  }
  if (errors.length > 0) fail(errors.join("; "));

  const manifest = await readJson(zip, "manifest.json");
  const script = await readJson(zip, "script.json");
  const checksum = await readJson(zip, "checksum.json");
  const gallery = zip.file("gallery.json") ? await readJson(zip, "gallery.json") : { gallery_version: "1.0.0", items: [] };

  const validationErrors = [];
  const validationWarnings = [];
  for (const field of ["manifest_version", "cartridge_version", "runtime_version", "game_id", "title", "author", "version", "entry_script", "entry_scene_id"]) {
    if (!manifest[field]) validationErrors.push(`manifest.json is missing required field: ${field}.`);
  }
  validationErrors.push(...validateScript(script));

  const manifestAssets = new Map((manifest.assets ?? []).map((asset) => [asset.asset_id, asset]));
  const assetByPath = new Map((manifest.assets ?? []).filter((asset) => asset.path).map((asset) => [asset.path, asset]));

  for (const [index, track] of (script.opening_audio ?? []).entries()) {
    if (!track?.asset_id) {
      validationErrors.push(`opening_audio.${index} is missing asset_id.`);
      continue;
    }
    const asset = manifestAssets.get(track.asset_id);
    if (!asset) continue;
    const playableType = ["bgm", "sfx", "voice"].includes(asset.asset_type)
      && asset.asset_type === track.asset_type
      && String(asset.mime_type ?? "").startsWith("audio/");
    if (!playableType) {
      validationErrors.push(`opening_audio.${index} asset ${track.asset_id} must be playable ${track.asset_type} audio (type=${asset.asset_type}, mime=${asset.mime_type ?? "missing"}).`);
    }
  }

  for (const ref of collectAssetRefs(script)) {
    if (!manifestAssets.has(ref)) {
      addAssetIssue({
        errors: validationErrors,
        warnings: validationWarnings,
        placeholderSafe: true,
        message: `Asset id is referenced by script but is not listed in manifest assets: ${ref}. Runtime will display/skip a placeholder when possible; replace it before publishing.`,
      });
    }
  }
  for (const scene of script.scenes ?? []) {
    for (const command of scene.commands ?? []) {
      if (command.type !== "show_image" || !command.image_id) continue;
      const asset = manifestAssets.get(command.image_id);
      if (!asset) continue;
      const imageLike = ["background", "sprite", "portrait", "ui"].includes(asset.asset_type) || String(asset.mime_type ?? "").startsWith("image/");
      if (!imageLike) {
        validationErrors.push(`show_image asset ${command.image_id} is not image-like (type=${asset.asset_type}, mime=${asset.mime_type ?? "missing"}).`);
      }
    }
  }
  for (const asset of manifest.assets ?? []) {
    if (!asset.path) {
      validationErrors.push(`Manifest asset ${asset.asset_id || "(unknown)"} is missing a path.`);
      continue;
    }
    if (!paths.includes(asset.path)) {
      addAssetIssue({
        errors: validationErrors,
        warnings: validationWarnings,
        placeholderSafe: isPlaceholderAsset(asset),
        message: `Manifest asset file is missing: ${asset.asset_id || "(unknown)"} -> ${asset.path}. Placeholder assets are allowed in standalone package builds, but should be replaced before publishing.`,
      });
    }
  }

  if (checksum.algorithm !== "sha256") {
    validationErrors.push(`Unsupported checksum algorithm: ${checksum.algorithm ?? "(missing)"}. Expected sha256.`);
  }
  for (const entry of checksum.files ?? []) {
    const file = zip.file(entry.path);
    if (!file) {
      addAssetIssue({
        errors: validationErrors,
        warnings: validationWarnings,
        placeholderSafe: isPlaceholderAsset(assetByPath.get(entry.path)),
        message: `checksum.json references a missing file: ${entry.path}.`,
      });
      continue;
    }
    const fileBuffer = Buffer.from(await file.async("uint8array"));
    if (fileBuffer.byteLength !== entry.size_bytes) {
      validationErrors.push(`Checksum size mismatch for ${entry.path}: expected ${entry.size_bytes}, got ${fileBuffer.byteLength}.`);
    }
    const hash = sha256(fileBuffer);
    if (hash !== entry.hash_sha256) {
      validationErrors.push(`Checksum hash mismatch for ${entry.path}.`);
    }
  }

  if (validationErrors.length > 0) fail(validationErrors.join("; "));
  warnings.push(...validationWarnings);

  const report = {
    ok: true,
    cartridge: cartridgePath,
    stream_read_bytes: buffer.byteLength,
    files: paths.length,
    game_id: manifest.game_id,
    title: manifest.title,
    scenes: Array.isArray(script.scenes) ? script.scenes.length : 0,
    assets: (manifest.assets ?? []).length,
    gallery_items: (gallery.items ?? []).length,
    entry_scene_id: script.entry_scene_id,
    client_readable: true,
    stream_input: true,
    zip_parser: "JSZip",
    allow_placeholder_assets: allowPlaceholderAssets,
    warnings,
  };
  publishReport(report);
}

main().catch((error) => {
  const report = { ok: false, cartridge: cartridgePath, error: error.message };
  if (reportPath) {
    try {
      writeJsonAtomic(reportPath, report);
    } catch (writeError) {
      process.stderr.write(`Failed to write verify report: ${writeError instanceof Error ? writeError.message : String(writeError)}\n`);
    }
  }
  process.stderr.write(`${JSON.stringify(report, null, 2)}\n`);
  process.exit(1);
});
